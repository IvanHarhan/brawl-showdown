// Однократно собирает maps/koeln.txt (60x60): Кёльнский собор у центра (D — не ломается),
// старый город из домов (#), Рейн с тремя мостами (W), парки (B), ящики (X), 10 спавнов.
// Дальше карту можно править руками. node tools/gen_koeln.mjs
import { writeFileSync } from 'node:fs';

const N = 60, C = N / 2;
const g = Array.from({ length: N }, () => Array(N).fill('.'));
const rect = (x, y, w, h, ch) => { for (let j = y; j < y + h; j++) for (let i = x; i < x + w; i++) if (g[j]?.[i] !== undefined) g[j][i] = ch; };

// Рейн по правой стороне и мосты: Северинсбрюкке, Хоэнцоллерн (широкий), Мюльхаймер
rect(49, 0, 3, N, 'W');
for (const [y, h] of [[11, 2], [28, 3], [46, 2]]) rect(49, y, 3, h, '.');

// Собор: западные башни шире нефа, апсида на востоке
rect(22, 17, 4, 8, 'D');   // башни
rect(26, 18, 10, 6, 'D');  // неф
rect(36, 19, 2, 4, 'D');   // апсида

// Старый город — кварталы домов
const houses = [
  [4, 4, 4, 2], [10, 4, 3, 2], [15, 4, 4, 2], [4, 9, 2, 4], [9, 9, 4, 2], [15, 9, 3, 3], [4, 16, 4, 2], [10, 15, 2, 4], [15, 14, 3, 2],
  [22, 4, 4, 2], [28, 4, 3, 2], [33, 4, 4, 2], [40, 4, 3, 3], [44, 9, 2, 4], [38, 10, 4, 2], [23, 10, 3, 2], [31, 10, 3, 2],
  [4, 24, 2, 4], [8, 22, 3, 2], [8, 31, 3, 2], [4, 34, 2, 4], [14, 27, 2, 5],
  [20, 34, 3, 2], [26, 37, 2, 3], [33, 34, 3, 2], [41, 30, 2, 4], [42, 24, 3, 2], [41, 16, 2, 3],
  [4, 43, 4, 2], [10, 41, 2, 4], [15, 45, 4, 2], [22, 45, 3, 2], [28, 43, 4, 2], [35, 45, 3, 2], [40, 40, 3, 3], [44, 47, 2, 4],
  [6, 51, 3, 2], [12, 53, 4, 2], [20, 51, 2, 3], [26, 53, 4, 2], [33, 51, 3, 2], [39, 54, 4, 2], [44, 53, 2, 3],
  // правый берег: Дойц
  [54, 14, 3, 2], [56, 25, 2, 3], [54, 41, 3, 2], [55, 56, 3, 2],
];
for (const [x, y, w, h] of houses) rect(x, y, w, h, '#');

// Парки: Штадтгартен, Рейнпарк, клумбы на Домплатте
const parks = [
  [16, 20, 3, 3], [17, 39, 4, 3], [36, 13, 3, 2], [30, 47, 3, 2], [5, 56, 4, 2], [1, 28, 2, 4],
  [54, 5, 4, 4], [55, 19, 3, 4], [54, 33, 4, 5], [55, 49, 3, 4], [20, 28, 2, 2], [37, 27, 2, 2], [28, 28, 4, 1],
];
for (const [x, y, w, h] of parks) rect(x, y, w, h, 'B');

// Ящики
const boxes = [
  [8, 7], [19, 7], [27, 7], [37, 7], [46, 4], [7, 13], [13, 13], [21, 14], [39, 15], [46, 17],
  [11, 20], [3, 21], [18, 26], [39, 21], [44, 28], [11, 28], [24, 30], [34, 29], [30, 33], [17, 33],
  [7, 38], [24, 40], [36, 39], [45, 36], [13, 48], [25, 48], [38, 48], [46, 43], [9, 57], [23, 57],
  [36, 57], [47, 57], [55, 3], [57, 11], [53, 28], [57, 38], [53, 46], [57, 54], [30, 15], [27, 26],
];
for (const [x, y] of boxes) g[y][x] = 'X';

// 10 спавнов по кругу; если попали в препятствие — сдвигаемся к центру
const free = (x, y) => g[y]?.[x] === '.' || g[y]?.[x] === 'B' || g[y]?.[x] === 'X';
for (let i = 0; i < 10; i++) {
  const a = (i / 10) * Math.PI * 2 - Math.PI / 2 + Math.PI / 10;
  let r = 24, sx, sy;
  do {
    sx = Math.round(C - 0.5 + Math.cos(a) * r); sy = Math.round(C - 0.5 + Math.sin(a) * r); r -= 0.5;
  } while (!free(sx, sy) && r > 5);
  for (let y = sy - 1; y <= sy + 1; y++) for (let x = sx - 1; x <= sx + 1; x++) if (g[y]?.[x] !== undefined && g[y][x] !== 'W' && g[y][x] !== 'D') g[y][x] = '.';
  g[sy][sx] = 'S';
}

const text = '; theme: koeln\n; Кёльн: собор у центра, Рейн с мостами, старый город\n' + g.map((r) => r.join('')).join('\n') + '\n';
writeFileSync(new URL('../maps/koeln.txt', import.meta.url), text);
